import os from "node:os"; import fs from "node:fs"; import path from "node:path";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { Store } from "../src/store/db.js";
import { createBus } from "../src/bus.js";
import { createLogger, setLogLevel } from "../src/logger.js";
import { resolveConfig, EXAMPLE_CONFIG, ensureDirs } from "../src/config.js";
import { createHarnessTools } from "../src/agents/tools.js";
setLogLevel("error");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "h-"));
const config = resolveConfig(EXAMPLE_CONFIG, root); ensureDirs(config);
const db = new Store(":memory:");
const ctx = { config, db, bus: createBus(db), log: createLogger("t"), runner: { run: async () => { throw new Error("x") }, active: () => [], cancel: () => false, cancelTask: () => 0 }, isPaused: () => false };
const { server, toolNames } = createHarnessTools(ctx as any, { agent: "chief" });
console.log(toolNames);
const [ct, st] = InMemoryTransport.createLinkedPair();
await server.instance.connect(st);
const client = new Client({ name: "test", version: "0" });
await client.connect(ct);
const list = await client.listTools();
console.log(list.tools.map(t => t.name));
const r = await client.callTool({ name: "list_leads", arguments: {} });
console.log(JSON.stringify(r).slice(0, 300));
const r2 = await client.callTool({ name: "get_task", arguments: { task_id: "nope" } });
console.log(JSON.stringify(r2));
await client.close(); await server.instance.close();
db.close();
